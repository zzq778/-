// Build the mobile workspace asset from the canonical Web modules.
import {readFileSync,writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFileSync(path.join(root,p),'utf8');
const entries={tourist:'public/portals/tourist/index.html',merchant:'public/portals/merchant/index.html',government:'public/portals/government/index.html',catalog:'public/wenlv-preview.html',itinerary:'public/itinerary-workspace.html',online:'public/portals/online/index.html'};
export function compile(readFile=read){
 const documents={};
 for(const [role,file] of Object.entries(entries)){
  const get=relative=>readFile(path.posix.normalize(path.posix.join(path.posix.dirname(file),relative)));
  let html=readFile(file).replace(/<link\b[^>]*rel="icon"[^>]*\/?>/g,'');
  html=html.replace(/<link\b[^>]*rel="stylesheet"[^>]*href="([^"]+)"[^>]*\/?>/g,(_,p)=>'<style>'+get(p)+'</style>');
  html=html.replace(/<script\s+src="([^"]+)"\s*><\/script>/g,(_,p)=>'<script>'+get(p).replace(/<\/script/gi,'<\\/script')+'</script>');
  const route=role==='catalog'?'tourist':'catalog';
  const href=role==='catalog'?'./index.html':'../../wenlv-preview.html';
  html=html.replaceAll('href="'+href+'"','href="#'+route+'" data-workspace-route="'+route+'"');
  const bridge='<script>document.addEventListener("click",function(e){var a=e.target.closest("[data-workspace-route]");if(!a)return;e.preventDefault();parent.postMessage({kind:"jzzx-workspace-route",role:a.dataset.workspaceRoute},"*");});</script>';
  html=html.replace('</body>',bridge+'</body>');
  if(/<script\s+src=|<link\b[^>]*rel="stylesheet"/i.test(html))throw Error('Unbundled resource in '+role);
  documents[role]=html;
 }
 // Shared data and styles occur in multiple workspaces; serialize each block once.
 const chunks=[],ids=new Map(),layouts={};
 for(const [role,html] of Object.entries(documents)){
  layouts[role]=html.split(/(<script\b[^>]*>[\s\S]*?<\/script>|<style\b[^>]*>[\s\S]*?<\/style>)/gi).filter(Boolean).map(block=>{
   if(!ids.has(block)){ids.set(block,chunks.length);chunks.push(block);}
   return ids.get(block);
  });
 }
 const payload=JSON.stringify([chunks,layouts]).replace(/</g,'\\u003c');
 return '/* Generated by scripts/build-mobile-workspaces.mjs. */\nwindow.JZZX_WORKSPACES=(([chunks,layouts])=>Object.fromEntries(Object.entries(layouts).map(([key,indices])=>[key,indices.map(i=>chunks[i]).join("")])))('+payload+');\n';
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 writeFileSync(path.join(root,'mobile/site/workspaces.js'),compile());
}
